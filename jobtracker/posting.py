"""Reading a pasted job posting without AI.

Postings copied from job sites come with page clutter (buttons, "8 hours ago", AI-generated summaries, company
blurbs) and the title is not always the first line: jobs.ch starts with the company and location, LinkedIn with the
title, company pages with a slogan. These rules score candidate lines instead of trusting position, and report how
sure they are, so the interface can highlight what to check.
"""

from __future__ import annotations

import re
from datetime import date

import pandas as pd

# --------------------------------------------------------------------------- page clutter
CLUTTER = re.compile(
    r"^\s*(save|saved|apply|apply now|easy apply|share|hide|show more|show less|see more|see less|see original|"
    r"display original ad|see company profile|follow|report this job|report job|promoted|actively recruiting|"
    r"check my match for this job|compare your cv with the requirements|results are ai-generated|is this helpful\?|"
    r"ai generated summary|ai-generated summary|this job ad was ai-translated from \w+\.?|"
    r"\d+\s+(?:minutes?|hours?|days?|weeks?|months?)\s+ago|reposted .*ago|posted .*ago|over \d+ applicants|"
    r"\d+ applicants|be an early applicant|\d+ jobs|\d+ - \d+ employees|\d+\+? employees|industry unspecified|"
    r"jetzt bewerben|bewerben|speichern|teilen|merken|vor \d+ (?:stunden|tagen|minuten)|"
    r"home|jobs|messaging|notifications|my network|me|for business|skip to main content)\s*$", re.I)

# Blocks that summarise or advertise rather than describe the job. Removed from the start heading up to the end.
SUMMARY_START = re.compile(r"^\s*(job summary|ai[- ]generated summary|summary generated by ai|key facts at a glance)\s*$", re.I)
SUMMARY_END = re.compile(r"^\s*(about the job|job description|description|the role|your role|your missions?|"
                         r"stellenbeschreibung|ihre aufgaben|about the position|position description)\s*:?\s*$", re.I)
TAIL_START = re.compile(r"^\s*(about the company|über das unternehmen|company profile|learn more about \w+|"
                        r"similar jobs|people also viewed|more jobs from|jobs you may be interested in|"
                        r"set alert for similar jobs|meet the hiring team)\s*$", re.I)


def clean(text: str) -> tuple[str, dict]:
    """Remove page clutter. Returns the cleaned text and what was removed (for an "undo" in the interface)."""
    lines = (text or "").replace("\r", "").split("\n")
    out, removed, skipping = [], {"clutter": 0, "summary": 0, "tail": 0}, False
    for i, ln in enumerate(lines):
        if TAIL_START.match(ln) and i > len(lines) * 0.4:
            removed["tail"] = len(lines) - i
            break
        if SUMMARY_START.match(ln):
            skipping = True
        if skipping:
            if SUMMARY_END.match(ln):
                skipping = False
            else:
                removed["summary"] += 1
                continue
        if CLUTTER.match(ln):
            removed["clutter"] += 1
            continue
        out.append(ln.rstrip())
    cleaned = re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()
    return cleaned, removed


# --------------------------------------------------------------------------- title and company
LEGAL = re.compile(r"\b(AG|SA|S\.A\.|SAS|SARL|Sàrl|GmbH|gGmbH|KG|Ltd\.?|Limited|LLC|LLP|Inc\.?|Corp\.?|plc|PLC|"
                   r"B\.?V\.?|N\.?V\.?|SE|S\.p\.A\.|SpA|S\.r\.l\.|AB|AS|A/S|Oy|ApS|Pte\.? Ltd|Pty Ltd|Co\.)\s*$")
ROLE_WORDS = re.compile(
    r"\b(engineer|engineering|analyst|scientist|manager|intern|internship|trainee|traineeship|graduate|associate|"
    r"specialist|consultant|developer|coordinator|assistant|officer|lead|director|representative|advisor|adviser|"
    r"administrator|technician|researcher|fellow|postdoc|phd|student|architect|designer|executive|head of|"
    r"partner|liaison|planner|auditor|controller|accountant|writer|editor|recruiter|owner|"
    r"praktikum|praktikant(?:in)?|werkstudent(?:in)?|mitarbeiter(?:in)?|sachbearbeiter(?:in)?|ingenieur(?:in)?|"
    r"berater(?:in)?|leiter(?:in)?|referent(?:in)?|spezialist(?:in)?|stagiaire|stage|ingénieur|chargé)\b", re.I)
GENDER_TAG = re.compile(r"\((?:m|w|d|f|x|all genders?|h/f|f/h|m/f|f/m|w/m|m/w)(?:\s*/\s*[mwdfxh])*\)", re.I)
HEADING = re.compile(r"^(about (the )?(job|role|us|company)|job description|description|requirements|responsibilities|"
                     r"your (profile|missions?|tasks|role)|what you|who you|tasks|skills|benefits|qualifications|"
                     r"ihr profil|ihre aufgaben|wir bieten|über uns)\b", re.I)
LABEL_TITLE = re.compile(r"^(?:job title|position|role|title|stelle|poste)\s*[:\-]\s*(.+)$", re.I)
LABEL_COMPANY = re.compile(r"^(?:company|employer|organisation|organization|firma|unternehmen|arbeitgeber)\s*[:\-]\s*(.+)$", re.I)
LABEL_LOCATION = re.compile(r"^(?:location|place of work|work location|arbeitsort|standort|lieu de travail|ort)\s*[:\-]\s*(.+)$", re.I)


def _short(ln: str, words: int = 12, chars: int = 90) -> bool:
    return 2 <= len(ln) <= chars and len(ln.split()) <= words and not ln.endswith((".", ":", "?", "!"))


def title_from_page(title: str) -> dict:
    """'Data Analyst - Norgine | LinkedIn', 'Data Analyst at Norgine', 'Norgine - Data Analyst'."""
    t = re.sub(r"\s*[|·]\s*(LinkedIn|Indeed.*|Glassdoor|jobs\.ch|jobup\.ch|Workday|Greenhouse|Lever|Stepstone.*|"
               r"XING|Monster.*|Welcome to the Jungle)\s*$", "", title or "", flags=re.I).strip()
    t = re.sub(r"^\(\d+\)\s*", "", t)
    m = re.match(r"(.+?)\s+(?:at|bei|chez)\s+(.+)$", t, re.I)
    if m:
        return {"position": m.group(1).strip(), "company": m.group(2).strip()}
    parts = [x.strip() for x in re.split(r"\s+[-–|]\s+", t) if x.strip()]
    if len(parts) >= 2:
        a, b = parts[0], parts[1]
        if ROLE_WORDS.search(b) and not ROLE_WORDS.search(a):  # "Norgine - Data Analyst"
            a, b = b, a
        return {"position": a, "company": b}
    if t and ROLE_WORDS.search(t):
        return {"position": t}
    if t:
        return {"company": t}
    return {}


def extract(raw: str, page_title: str | None = None, places=None) -> dict:
    """Best guesses for the main fields, each with a confidence: 'high', 'medium' or 'low'."""
    text = raw or ""
    lines = [ln.strip(" \t•-–|*") for ln in text.replace("\r", "").split("\n")]
    lines = [ln for ln in lines if ln and not CLUTTER.match(ln)]
    head = lines[:25]
    conf: dict[str, str] = {}
    company = position = location = None

    for ln in lines[:40]:
        if not position and (m := LABEL_TITLE.match(ln)):
            position, conf["position"] = m.group(1).strip(), "high"
        if not company and (m := LABEL_COMPANY.match(ln)):
            company, conf["company"] = m.group(1).strip(), "high"
        if not location and (m := LABEL_LOCATION.match(ln)):
            location, conf["location"] = m.group(1).strip(), "high"

    # LinkedIn-style "Company · City, Country (Hybrid)" line.
    for ln in head[:8]:
        if " · " in ln and not ROLE_WORDS.search(ln.split(" · ")[0]):
            first, rest = ln.split(" · ", 1)
            if not company and _short(first, 8, 70):
                company, conf["company"] = first.strip(), "high"
            loc = re.sub(r"\((?:hybrid|remote|on-?site)\)", "", rest.split(" · ")[0], flags=re.I).strip()
            if not location and loc and not re.search(r"ago|applicant", loc, re.I):
                location, conf["location"] = loc, "high"
            break

    # Company: a line after "About the company", a legal suffix, or a short line repeated in the posting.
    if not company:
        for i, ln in enumerate(lines):
            if TAIL_START.match(ln) and i + 1 < len(lines) and _short(lines[i + 1], 8, 70):
                company, conf["company"] = lines[i + 1], "high"
                break
    if not company:
        for ln in head:
            if _short(ln, 8, 70) and LEGAL.search(ln) and not ROLE_WORDS.search(ln):
                company, conf["company"] = ln, "high"
                break
    if not company:
        counts = pd.Series([ln for ln in lines if _short(ln, 6, 60) and not HEADING.match(ln)]).value_counts()
        rep = [c for c, n in counts.items() if n >= 2 and not ROLE_WORDS.search(c) and not re.search(r"\d", c)]
        if rep:
            company, conf["company"] = rep[0], "medium"
    if not company:
        for pat in (r"^([A-Z][\w&.'\- ]{1,40}?)\s+(?:is|are)\s+(?:hiring|looking|seeking|searching|recruiting)\b",
                    r"^About\s+([A-Z][\w&.'\- ]{1,40}?)\s*$",
                    r"\b(?:join|joining)\s+([A-Z][\w&.'\-]+(?: [A-Z][\w&.'\-]+){0,3})(?:[,.!]| is | as | we | and | to |$)"):
            m = re.search(pat, text, re.M)
            if m and m.group(1).strip().lower() not in {"we", "our", "you", "they", "it", "this", "the team", "us"}:
                company, conf["company"] = m.group(1).strip(), "low"
                break

    # Position: the highest-scoring short line near the top that reads like a job title.
    if not position:
        best, best_score = None, 0.0
        for i, ln in enumerate(head):
            if not _short(ln, 14, 110) or HEADING.match(ln) or (company and ln.lower() == company.lower()) \
                    or re.search(r"[.!?]\s+\S", ln) or re.match(r"(we|you|our|join|are you)\b", ln, re.I):
                continue
            score = 0.0
            if ROLE_WORDS.search(ln):
                score += 3
            if GENDER_TAG.search(ln) or re.search(r"\b\d{2,3}\s*(?:-|–)?\s*\d{0,3}\s*%", ln) and ROLE_WORDS.search(ln):
                score += 1.5
            if re.search(r"\b(senior|junior|lead|principal|head|chief|vp)\b", ln, re.I):
                score += 0.5
            score -= i * 0.08  # earlier lines are a little more likely
            if re.search(r"\d{4}|%$|^\d", ln) and not ROLE_WORDS.search(ln):
                score -= 3
            if score > best_score:
                best, best_score = ln, score
        if best and best_score >= 2.5:
            position, conf["position"] = GENDER_TAG.sub("", best).strip(" -–,"), "high" if best_score >= 3 else "medium"
        elif head and _short(head[0]) and head[0] != company:
            position, conf["position"] = head[0], "low"

    # The page title (sent by the browser bookmark) is usually the cleanest source.
    page = title_from_page(page_title or "")
    labelled = {k for k in ("position", "company") if conf.get(k) == "high" and k == "position" and LABEL_TITLE.search(text)}
    if page.get("position") and "position" not in labelled and (ROLE_WORDS.search(page["position"]) or conf.get("position") != "high"):
        position, conf["position"] = page["position"], "high" if ROLE_WORDS.search(page["position"]) else "medium"
    if page.get("company") and conf.get("company") != "high":
        company, conf["company"] = page["company"], "medium"

    # Location: the line under the company when it looks like "Town, Town" (jobs.ch puts it there).
    if not location and company and company in lines[:6]:
        i = lines.index(company)
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        if _short(nxt, 10, 90) and nxt != position and not ROLE_WORDS.search(nxt) and not re.search(r"\d", nxt) \
                and all(w[:1].isupper() for w in re.split(r"[,\s/]+", nxt) if w and w.lower() not in {"and", "or", "de", "en", "sur", "am", "im"}):
            location, conf["location"] = nxt, "medium"

    # Location: a known place in a short line near the title/company.
    if not location and places:
        for ln in head[:12]:
            if not _short(ln, 10, 90) or ln in (company, position):
                continue
            for rx, name, *_ in places:
                if rx.search(ln):
                    location, conf["location"] = ln, "medium"
                    break
            if location:
                break

    if position:  # "Data Engineer - INTERNSHIP" -> "Data Engineer - Internship"; workload goes in its own field
        position = re.sub(r"\s*\(?\b\d{2,3}\s*(?:%\s*)?(?:-|–|to|bis)?\s*\d{0,3}\s*%\)?", "", position).strip(" -–,")
        position = re.sub(r"\b([A-Z]{4,})\b", lambda m: m.group(1).capitalize(), position)
    return {"position": position, "company": company, "location": location, "workload": workload(text),
            "contract": contract(text), "deadline": deadline(text), "language": language(text), "confidence": conf}


# --------------------------------------------------------------------------- other fields
def workload(text: str) -> str | None:
    m = re.search(r"(?<![\d.])(\d{2,3})\s*(?:%\s*)?(?:-|–|to|bis)\s*(\d{2,3})\s*%", text or "")
    if m and int(m.group(2)) <= 100:
        return f"{m.group(1)}–{m.group(2)}%"
    m = re.search(r"(?:^|\s|\()(\d{2,3})\s*%(?:\s|$|\)|,)", text or "", re.M)
    if m and 20 <= int(m.group(1)) <= 100:
        return f"{m.group(1)}%"
    return None


CONTRACTS = [
    ("Internship", r"\b(internship|intern\b|praktikum|praktikant|stage\b|stagiaire|trainee(?:ship)?)"),
    ("Fixed-term", r"\b(fixed[- ]term|temporary contract|befristet|\d+[- ]months? (?:contract|position)|contrat à durée déterminée|cdd\b|maternity cover)"),
    ("Freelance", r"\b(freelance|contractor\b|self-employed)"),
    ("Permanent", r"\b(permanent|unbefristet|festanstellung|open[- ]ended|cdi\b)"),
]


def contract(text: str) -> str | None:
    low = (text or "").lower()
    for name, pat in CONTRACTS:
        if re.search(pat, low):
            return name
    return None


MONTHS = {m: i for i, m in enumerate(["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"], 1)}
MONTHS.update({"mär": 3, "mai": 5, "okt": 10, "dez": 12, "janv": 1, "févr": 2, "mars": 3, "avr": 4, "juin": 6,
               "juil": 7, "août": 8, "sept": 9, "déc": 12})


def _date(s: str) -> str | None:
    s = s.strip()
    m = re.match(r"(\d{1,2})[./](\d{1,2})[./](\d{2,4})", s)
    if m:
        d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
        y = y + 2000 if y < 100 else y
    else:
        m = re.match(r"(\d{1,2})\.?\s+([A-Za-zäéû]{3,9})\.?\s+(\d{4})", s) or None
        if m:
            d, mo, y = int(m.group(1)), MONTHS.get(m.group(2)[:4].lower().rstrip(".")) or MONTHS.get(m.group(2)[:3].lower()), int(m.group(3))
        else:
            m = re.match(r"([A-Za-z]{3,9})\.?\s+(\d{1,2}),?\s+(\d{4})", s)
            if not m:
                return None
            d, mo, y = int(m.group(2)), MONTHS.get(m.group(1)[:3].lower()), int(m.group(3))
    try:
        return date(y, mo, d).isoformat() if mo else None
    except (ValueError, TypeError):
        return None


def deadline(text: str) -> str | None:
    m = re.search(r"(?:apply by|application deadline|deadline(?: for applications)?|closing date|applications close|"
                  r"apply before|bewerbungsfrist|bewerben sie sich bis|bewerbung bis|bis zum|date limite)\s*[:\-]?\s*"
                  r"(?:on\s+|am\s+|le\s+)?([0-9]{1,2}[./][0-9]{1,2}[./][0-9]{2,4}|[0-9]{1,2}\.?\s+[A-Za-zäéû]{3,9}\.?\s+[0-9]{4}|"
                  r"[A-Za-z]{3,9}\.?\s+[0-9]{1,2},?\s+[0-9]{4})", text or "", re.I)
    return _date(m.group(1)) if m else None


DE = {"und", "der", "die", "das", "mit", "für", "wir", "sie", "ihre", "eine", "einen", "von", "zu", "ist", "bei", "auf",
      "oder", "werden", "unser", "unsere", "sowie", "sind", "im", "in", "den", "dem"}
EN = {"and", "the", "with", "for", "we", "you", "your", "our", "a", "an", "of", "to", "is", "at", "on", "or", "will",
      "are", "be", "in", "as", "this", "that"}


def language(text: str) -> str:
    """'de', 'en' or 'other' from common short words."""
    words = re.findall(r"[a-zäöüß]+", (text or "").lower())
    if len(words) < 30:
        return "en"
    de = sum(w in DE for w in words)
    en = sum(w in EN for w in words)
    if de > en * 1.2 and de >= 8:
        return "de"
    if en >= de:
        return "en"
    return "other"
